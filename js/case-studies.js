function initPipeline() {
  const track = document.getElementById("pipeline-track");
  const panel = document.getElementById("pipeline-detail");
  if (!track || !panel) return;

  track.innerHTML = pipelineStages
    .map(
      (s, i) => `
    <button class="pipe-stage${i === 0 ? " active" : ""}" data-stage="${s.id}"
            role="tab" aria-selected="${i === 0}" aria-controls="pipeline-detail" id="pipe-tab-${s.id}">
      <span class="pipe-num">${i + 1}</span>
      <span class="pipe-label">${s.label}</span>
      <span class="pipe-caption">${s.caption}</span>
    </button>`
    )
    .join("");

  function show(id) {
    const stage = pipelineStages.find((s) => s.id === id);
    if (!stage) return;
    track.querySelectorAll(".pipe-stage").forEach((b) => {
      const on = b.getAttribute("data-stage") === id;
      b.classList.toggle("active", on);
      b.setAttribute("aria-selected", String(on));
    });
    panel.setAttribute("aria-labelledby", `pipe-tab-${id}`);
    panel.innerHTML = `
      <h3 class="pipe-detail-title">${stage.label}</h3>
      <p class="pipe-detail-text">${stage.detail}</p>
      <ul class="pipe-outputs">
        ${stage.outputs.map((o) => `<li class="pipe-output">${o}</li>`).join("")}
      </ul>`;
    panel.classList.remove("swap");
    void panel.offsetWidth;
    panel.classList.add("swap");
  }

  track.querySelectorAll(".pipe-stage").forEach((btn) => {
    btn.addEventListener("click", () => show(btn.getAttribute("data-stage")));
    btn.addEventListener("keydown", (e) => {
      const btns = [...track.querySelectorAll(".pipe-stage")];
      const i = btns.indexOf(btn);
      let next = null;
      if (e.key === "ArrowRight" || e.key === "ArrowDown") next = btns[(i + 1) % btns.length];
      if (e.key === "ArrowLeft" || e.key === "ArrowUp") next = btns[(i - 1 + btns.length) % btns.length];
      if (next) {
        e.preventDefault();
        next.focus();
        show(next.getAttribute("data-stage"));
      }
    });
  });

  show(pipelineStages[0].id);
}

