/* ------------------------------------------------------------
   Seeded PRNG (mulberry32) — deterministic, so the "data" is
   identical on every load and can never be mistaken for a live feed.
   ------------------------------------------------------------ */
function makeRng(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

