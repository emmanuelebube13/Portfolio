/* ============================================================
   STAT TILE COUNTERS (motion & polish)
   ============================================================ */
function initCounters() {
  const els = document.querySelectorAll("[data-count-to]");
  if (!els.length) return;
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        const el = entry.target;
        io.unobserve(el);
        const to = parseFloat(el.getAttribute("data-count-to"));
        const suffix = el.getAttribute("data-suffix") || "";
        // The true value is already in the markup, so a visitor whose
        // browser never runs this sees the number, not a zero.
        if (prefersReducedMotion()) {
          el.textContent = to.toLocaleString() + suffix;
          return;
        }
        const dur = 1100;
        const t0 = performance.now();
        (function step(now) {
          const p = Math.min(1, (now - t0) / dur);
          const e = 1 - Math.pow(1 - p, 3);
          el.textContent = Math.round(to * e).toLocaleString() + suffix;
          if (p < 1) requestAnimationFrame(step);
        })(performance.now());
        // The tile shows a number — never leave it stuck mid-count.
        setTimeout(() => {
          el.textContent = to.toLocaleString() + suffix;
        }, dur + 200);
      });
    },
    { threshold: 0.5 }
  );
  els.forEach((el) => io.observe(el));
}

