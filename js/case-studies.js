function buildMapData() {
  const rnd = makeRng(20260808);
  const institutions = [
    { name: "Institution A", x: 236, y: 214 },
    { name: "Institution B", x: 404, y: 168 },
    { name: "Institution C", x: 560, y: 214 },
    { name: "Institution D", x: 330, y: 330 },
    { name: "Institution E", x: 520, y: 318 },
  ];

  // Cluster respondents loosely around institutions, with scatter.
  const pts = [];
  const perCluster = 22;
  institutions.forEach((inst, ci) => {
    for (let i = 0; i < perCluster; i++) {
      const ang = rnd() * Math.PI * 2;
      const rad = Math.pow(rnd(), 0.62) * 108;
      const x = inst.x + Math.cos(ang) * rad;
      const y = inst.y + Math.sin(ang) * rad * 0.78;
      if (x < 110 || x > 640 || y < 118 || y > 396) continue;
      // Commute rises with distance from the nearest institution.
      const commute = Math.round(8 + (rad / 108) * 46 + rnd() * 12);
      // Housing cost share falls slightly as you move outward.
      const share = Math.round(52 - (rad / 108) * 18 + rnd() * 12);
      pts.push({ id: `R-${ci}${String(i).padStart(2, "0")}`, x, y, commute, share, cluster: ci });
    }
  });
  return { institutions, points: pts };
}

