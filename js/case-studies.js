function initLedger() {
  const host = document.getElementById("ledger-chart");
  if (!host) return;
  const toggle = document.getElementById("ledger-toggle");
  const tableBtn = document.getElementById("ledger-table-btn");
  const tableHost = document.getElementById("ledger-table");
  const caption = document.getElementById("ledger-caption");

  let mode = "intake";
  const BAR = 22;      // <= 24px marks
  const GAP = 20;
  const TOP = 8;
  const max = Math.max(...ledgerClasses.map((d) => d.intake));

  function render(animate) {
    const w = host.clientWidth || 700;
    // Narrow screens cannot afford a label column beside the bars, so the
    // label moves above its bar and the bar gets the full width.
    const compact = w < 560;
    const LEFT = compact ? 0 : 230;
    const RIGHT = compact ? 54 : 62;
    const ROW = compact ? BAR + GAP + 18 : BAR + GAP;
    const plotW = Math.max(90, w - LEFT - RIGHT);
    const h = TOP + ledgerClasses.length * ROW;

    host.innerHTML = "";
    const svg = svgEl("svg", {
      viewBox: `0 0 ${w} ${h}`,
      width: "100%",
      height: h,
      role: "img",
      "aria-label":
        mode === "intake"
          ? "Bar chart, synthetic: records flagged at intake by issue class."
          : "Bar chart, synthetic: records still unresolved after cleaning, by issue class.",
    });

    // Baseline — solid hairline, recessive.
    svg.appendChild(
      svgEl("line", { x1: LEFT, y1: TOP, x2: LEFT, y2: h - GAP + 6, stroke: VIZ.axis, "stroke-width": 1 })
    );

    ledgerClasses.forEach((d, i) => {
      const y = TOP + i * ROW + (compact ? 18 : 0);
      const val = mode === "intake" ? d.intake : d.remaining;
      const target = (val / max) * plotW;

      const label = svgEl("text", {
        x: compact ? 0 : LEFT - 12,
        y: compact ? y - 7 : y + BAR / 2 + 4,
        "text-anchor": compact ? "start" : "end",
        fill: VIZ.ink2, "font-size": compact ? "12" : "12.5", "font-family": "inherit",
      });
      label.textContent = d.name;
      svg.appendChild(label);

      const bar = svgEl("path", {
        d: barPathH(LEFT, y, animate ? 0 : target, BAR, 4),
        fill: VIZ.series,
      });
      svg.appendChild(bar);

      const value = svgEl("text", {
        x: LEFT + target + 10, y: y + BAR / 2 + 4,
        fill: VIZ.ink2, "font-size": "12.5", "font-family": "inherit",
        "font-variant-numeric": "tabular-nums",
      });
      value.textContent = val.toLocaleString();
      if (animate) value.setAttribute("opacity", "0");
      svg.appendChild(value);

      if (animate) {
        const dur = prefersReducedMotion() ? 0 : 620;
        const delay = prefersReducedMotion() ? 0 : i * 70;
        const settle = () => {
          bar.setAttribute("d", barPathH(LEFT, y, target, BAR, 4));
          value.setAttribute("x", LEFT + target + 10);
          value.setAttribute("opacity", "1");
        };
        const t0 = performance.now() + delay;
        (function step(now) {
          const p = dur === 0 ? 1 : Math.min(1, Math.max(0, (now - t0) / dur));
          const e = 1 - Math.pow(1 - p, 3);
          bar.setAttribute("d", barPathH(LEFT, y, target * e, BAR, 4));
          value.setAttribute("x", LEFT + target * e + 10);
          value.setAttribute("opacity", String(e));
          if (p < 1) requestAnimationFrame(step);
        })(performance.now());
        // The bar carries the value — guarantee the end state regardless
        // of whether animation frames ever arrive.
        setTimeout(settle, delay + dur + 150);
      }
    });

    host.appendChild(svg);
    if (caption) {
      caption.textContent =
        mode === "intake"
          ? "Records flagged at intake, by issue class. Synthetic counts."
          : "Records still unresolved after the cleaning pass. Missing values are kept as missing rather than imputed, so that class does not go to zero.";
    }
  }

  function renderTable() {
    if (!tableHost) return;
    tableHost.innerHTML = `
      <table class="viz-table">
        <caption>Cleaning ledger — synthetic counts</caption>
        <thead>
          <tr><th scope="col">Issue class</th><th scope="col">Flagged at intake</th><th scope="col">Unresolved after</th><th scope="col">Handling</th></tr>
        </thead>
        <tbody>
          ${ledgerClasses
            .map(
              (d) =>
                `<tr><th scope="row">${d.name}</th><td>${d.intake.toLocaleString()}</td><td>${d.remaining.toLocaleString()}</td><td>${d.note}</td></tr>`
            )
            .join("")}
        </tbody>
      </table>`;
  }

  if (toggle) {
    toggle.querySelectorAll("[data-mode]").forEach((btn) => {
      btn.addEventListener("click", () => {
        mode = btn.getAttribute("data-mode");
        toggle.querySelectorAll("[data-mode]").forEach((b) => {
          const on = b === btn;
          b.classList.toggle("active", on);
          b.setAttribute("aria-pressed", String(on));
        });
        render(true);
      });
    });
  }

  if (tableBtn && tableHost) {
    tableBtn.addEventListener("click", () => {
      const open = tableHost.classList.toggle("open");
      tableBtn.setAttribute("aria-expanded", String(open));
      tableBtn.textContent = open ? "Hide data table" : "Show data table";
      if (open) renderTable();
    });
  }

  render(false);
  // Animate once when scrolled into view.
  let played = false;
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting && !played) {
          played = true;
          render(true);
        }
      });
    },
    { threshold: 0.25 }
  );
  io.observe(host);

  let rt;
  window.addEventListener("resize", () => {
    clearTimeout(rt);
    rt = setTimeout(() => render(false), 180);
  });
}

